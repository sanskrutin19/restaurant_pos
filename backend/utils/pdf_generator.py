from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_RIGHT, TA_LEFT
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, HRFlowable, PageBreak
from reportlab.lib.units import cm, inch
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.graphics.shapes import Drawing, Rect
from reportlab.graphics.charts.piecharts import Pie
from reportlab.graphics.charts.barcharts import HorizontalBarChart
import io
import os
from datetime import datetime

class PDFGenerator:
    MODERN_BLUE = colors.Color(37/255, 99/255, 235/255) # #2563EB
    LIGHT_BLUE = colors.Color(219/255, 234/255, 254/255) # #DBEAFE
    TEXT_GRAY = colors.Color(107/255, 114/255, 128/255) # #6B7280

    @staticmethod
    def _register_fonts():
        try:
            font_paths = [
                "C:\\Windows\\Fonts\\arial.ttf",
                "C:\\Windows\\Fonts\\Arial.ttf",
                os.path.expandvars("%WINDIR%\\Fonts\\arial.ttf")
            ]
            for path in font_paths:
                if os.path.exists(path):
                    pdfmetrics.registerFont(TTFont('Arial', path))
                    return 'Arial'
        except: pass
        return 'Helvetica'

    @staticmethod
    def _create_footer(canvas, doc, restaurant_name):
        canvas.saveState()
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(PDFGenerator.TEXT_GRAY)
        footer_text = f"Generated by {restaurant_name} POS System | Page {doc.page}"
        canvas.drawCentredString(A4[0]/2, 1*cm, footer_text)
        canvas.restoreState()

    @staticmethod
    def generate_sales_pdf(data: dict, start_date: datetime, end_date: datetime, restaurant_name: str, orientation: str = 'portrait'):
        buffer = io.BytesIO()
        font_name = PDFGenerator._register_fonts()
        page_size = landscape(A4) if orientation == 'landscape' else A4
        
        # Determine margins
        doc = SimpleDocTemplate(
            buffer, 
            pagesize=page_size, 
            rightMargin=1.5*cm, leftMargin=1.5*cm, topMargin=2*cm, bottomMargin=2*cm
        )
        elements = []
        styles = getSampleStyleSheet()
        
        # Custom Styles
        title_style = ParagraphStyle('Title', parent=styles['Heading1'], fontSize=26, textColor=PDFGenerator.MODERN_BLUE, alignment=TA_CENTER, spaceAfter=10)
        subtitle_style = ParagraphStyle('Subtitle', fontSize=14, alignment=TA_CENTER, spaceAfter=20, textColor=colors.black)
        section_style = ParagraphStyle('Section', fontSize=16, textColor=colors.white, backColor=PDFGenerator.MODERN_BLUE, 
                                      alignment=TA_LEFT, spaceBefore=15, spaceAfter=10, leftIndent=5, borderPadding=5)
        
        # 1. HEADER
        elements.append(Paragraph(restaurant_name.upper(), title_style))
        elements.append(Paragraph("SALES REPORT", subtitle_style))
        elements.append(Paragraph(f"Period: {start_date.strftime('%d/%m/%Y')} to {end_date.strftime('%d/%m/%Y')}", styles['Normal']))
        elements.append(Paragraph(f"Generated On: {datetime.now().strftime('%d/%m/%Y %H:%M')}", ParagraphStyle('gen', parent=styles['Normal'], alignment=TA_RIGHT)))
        elements.append(HRFlowable(width="100%", thickness=2, color=PDFGenerator.MODERN_BLUE, spaceAfter=20))

        # 2. EXECUTIVE SUMMARY
        elements.append(Paragraph("EXECUTIVE SUMMARY", section_style))
        s = data['summary']
        summary_data = [
            ['Metric', 'Value'],
            ['Total Revenue', f"\u20B9 {s['total_revenue']:.2f}"],
            ['Total Orders', str(s['total_orders'])],
            ['Total Tax', f"\u20B9 {s['total_tax']:.2f}"],
            ['CGST', f"\u20B9 {s['cgst']:.2f}"],
            ['SGST', f"\u20B9 {s['sgst']:.2f}"],
            ['Total Discount', f"\u20B9 {s['discount']:.2f}"]
        ]
        
        summary_table = Table(summary_data, colWidths=[8*cm, 5*cm])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), PDFGenerator.MODERN_BLUE),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, -1), font_name),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 12),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.lightgrey),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.Color(0.97, 0.98, 0.99)])
        ]))
        elements.append(summary_table)
        elements.append(Spacer(1, 1*cm))

        # 3. TOP ITEMS CHART (Horizontal Bar)
        if data['item_wise']:
            elements.append(Paragraph("TOP SELLING ITEMS", section_style))
            top_items = data['item_wise'][:10]
            drawing = Drawing(400, 200)
            bc = HorizontalBarChart()
            bc.x = 100; bc.y = 20; bc.height = 150; bc.width = 300
            bc.data = [[row['total_revenue'] for row in top_items]]
            bc.categoryAxis.categoryNames = [row['item_name'] for row in top_items]
            bc.bars[0].fillColor = PDFGenerator.MODERN_BLUE
            bc.valueAxis.valueMin = 0
            drawing.add(bc)
            elements.append(drawing)
            elements.append(Spacer(1, 1*cm))

        # 4. CATEGORY BREAKDOWN (Pie Chart)
        if data['category_wise']:
            elements.append(Paragraph("CATEGORY-WISE DISTRIBUTION", section_style))
            drawing = Drawing(400, 200)
            pc = Pie()
            pc.x = 150; pc.y = 50; pc.width = 150; pc.height = 150
            pc.data = [row['total_revenue'] for row in data['category_wise']]
            pc.labels = [row['category'] for row in data['category_wise']]
            pc.slices.strokeWidth=0.5
            pc.slices[0].fillColor = PDFGenerator.MODERN_BLUE
            drawing.add(pc)
            elements.append(drawing)
            elements.append(Spacer(1, 1*cm))

        # 5. PAYMENT METHODS (with Icons)
        elements.append(Paragraph("PAYMENT BREAKDOWN", section_style))
        pay_icons = {"Cash": "\U0001F4B5", "UPI": "\U0001F4F1", "Card": "\U0001F4B3"}
        pay_data = [['Method', 'Count', 'Total Amount']]
        for p in data['payment_breakdown']:
            icon = pay_icons.get(p['mode'], "")
            pay_data.append([f"{icon} {p['mode']}", str(p['count']), f"\u20B9 {p['total_amount']:.2f}"])
        
        pay_table = Table(pay_data, colWidths=[6*cm, 3*cm, 4*cm])
        pay_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), PDFGenerator.MODERN_BLUE),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, -1), font_name),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.lightgrey)
        ]))
        elements.append(pay_table)
        
        # Build document with footer
        doc.build(elements, onFirstPage=lambda c, d: PDFGenerator._create_footer(c, d, restaurant_name), 
                  onLaterPages=lambda c, d: PDFGenerator._create_footer(c, d, restaurant_name))
        
        pdf = buffer.getvalue()
        buffer.close()
        return pdf
